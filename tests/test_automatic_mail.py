@pytest.mark.parametrize(
    "subject",
    [
        "I'll be out of office Friday",
        "Planning our out of office coverage",
        "Re: Out of office",
        "Out of office coverage for Monday",
        "Automatic reply settings need fixing",
        "My automatic reply is wrong",
        "Draft for Mira",
        "",
        "Out of officer training",
        "Discuss the Abwesenheitsnotiz tomorrow",
    ],
)
def test_personal_subjects_are_not_substring_matches(subject):
    assert classify_automatic({}, subject, "text/plain") == Classification("none", None)


@pytest.mark.parametrize(
    "headers",
    [
        {"Auto-Submitted": "no"},
        {"Auto-Submitted": "unknown"},
        {"Precedence": "normal"},
        {"X-Auto-Response-Suppress": "All"},
        {"X-Auto-Response-Suppress": "OOF, AutoReply"},
        {"X-Loop": "rowan@example.com"},
        {"Return-Path": "<>"},
        {"List-Unsubscribe": "<mailto:leave@example.com>"},
        {"X-Autoreply": "no"},
        {"X-Autorespond": "false"},
        {"X-Autogenerated": "unknown"},
        {"X-MS-Exchange-Generated-Message-Source": "Mailbox Rules Agent"},
        {"List-Id": "invalid"},
    ],
)
def test_nondeciding_headers(headers):
    assert classify_automatic(headers, "Draft review", "text/plain").kind == "none"


def test_auto_submitted_no_prevents_subject_only_classification():
    assert classify_automatic({"Auto-Submitted": "no"}, "Out of office", "text/plain").kind == "none"


def test_dsn_overrides_auto_generated_and_precedence():
    assert (
        classify_automatic(
            {"Auto-Submitted": "auto-generated", "Precedence": "bulk"},
            "Automatic reply",
            "multipart/report; report-type=delivery-status",
        ).kind
        == "bounce"
    )


def test_specific_list_or_bulk_beats_generic_generated():
    assert (
        classify_automatic({"Auto-Submitted": "auto-generated", "Precedence": "bulk"}, "Notes", "text/plain").kind
        == "bulk"
    )


def test_list_beats_bulk_but_auto_reply_beats_list():
    headers = {"List-Id": "Notes <notes.example.com>", "Precedence": "bulk"}
    assert classify_automatic(headers, "Draft", "text/plain").kind == "list"
    headers["Auto-Submitted"] = "auto-replied"
    assert classify_automatic(headers, "Draft", "text/plain").kind == "auto_reply"


def test_read_receipt_is_not_delivery_failure():
    assert (
        classify_automatic({}, "Read: Draft", "multipart/report; report-type=disposition-notification").kind == "none"
    )


def test_message_object_and_repeated_headers():
    message = Message()
    message["Auto-Submitted"] = "no"
    message["Auto-Submitted"] = "auto-replied"
    assert classify_automatic(message, "Draft", "text/plain").kind == "auto_reply"
    assert classify_automatic({"Auto-Submitted": ["no", "auto-replied"]}, "Draft", "text/plain").kind == "auto_reply"
    assert classify_automatic([("Precedence", "bulk")], "Draft", "text/plain").kind == "bulk"


def test_personal_body_is_not_examined():
    message = Message()
    message["From"] = "mira@example.com"
    message["To"] = "rowan@example.com"
    message.set_payload("I will be out of office Friday, but I'll send the draft Thursday.")
    assert classify_automatic(message, "The draft", "text/plain").kind == "none"


def test_repeatable_and_does_not_change_headers():
    headers = {"Precedence": ["bulk"]}
    assert classify_automatic(headers, "Notes", "text/plain") == classify_automatic(headers, "Notes", "text/plain")
    assert headers == {"Precedence": ["bulk"]}


def test_generated_mail_is_not_an_automatic_reply():
    result = classify_automatic({"Auto-Submitted": "auto-generated"}, "Your receipt", "text/plain")
    assert result == Classification("generated", "Auto-Submitted: auto-generated")
