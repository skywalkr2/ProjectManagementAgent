"""Fictional headers and subjects with no message-body classification."""

from email.message import Message

import pytest

from engine.automatic_mail import Classification, classify_automatic


@pytest.mark.parametrize(
    "header,value,kind",
    [
        ("Auto-Submitted", "auto-replied", "auto_reply"),
        ("Auto-Submitted", "auto-generated", "generated"),
        ("auto-submitted", "AUTO-REPLIED; owner-email=mira@example.com", "auto_reply"),
        ("X-Autoreply", "yes", "auto_reply"),
        ("X-Auto-Reply", "true", "auto_reply"),
        ("X-Autorespond", "oof", "auto_reply"),
        ("X-Autoresponse", "1", "auto_reply"),
        ("X-Auto-Response", "vacation", "auto_reply"),
        ("X-Autoreply-From", "mira@example.com", "auto_reply"),
        ("X-Autogenerated", "Reply", "auto_reply"),
        ("X-MS-Exchange-Organization-AutoReply", "true", "auto_reply"),
        ("Precedence", "bulk", "bulk"),
        ("Precedence", "junk", "bulk"),
        ("Precedence", "list", "list"),
        ("Precedence", "auto_reply", "auto_reply"),
        ("List-Id", "Workshop notes <notes.example.com>", "list"),
        ("X-Failed-Recipients", "oren@example.com", "bounce"),
    ],
)
def test_deciding_headers(header, value, kind):
    assert classify_automatic({header: value}, "Draft", "text/plain") == Classification(kind, f"{header}: {value}")


@pytest.mark.parametrize(
    "content_type",
    [
        'multipart/report; report-type=delivery-status; boundary="fictional-boundary"',
        'Multipart/Report; REPORT-TYPE="delivery-status"',
        "message/delivery-status",
        "message/global-delivery-status",
        'multipart/report;\r\n report-type=delivery-status; boundary="draft-boundary"',
        "multipart/report; report-type=global-delivery-status",
    ],
)
def test_delivery_reports(content_type):
    assert classify_automatic({}, "Delivery report", content_type) == Classification(
        "bounce", "Content-Type: " + content_type
    )


